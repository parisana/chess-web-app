CREATE TABLE games (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    white_player_id BIGINT NOT NULL,
    black_player_id BIGINT NOT NULL,
    status VARCHAR(30) NOT NULL,
    current_fen TEXT NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
        DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_games_white_player
        FOREIGN KEY (white_player_id)
        REFERENCES players(id),

    CONSTRAINT fk_games_black_player
        FOREIGN KEY (black_player_id)
        REFERENCES players(id),

    CONSTRAINT ck_games_distinct_players
        CHECK (white_player_id <> black_player_id),

    CONSTRAINT ck_games_status
        CHECK (status IN ('IN_PROGRESS')),

    CONSTRAINT ck_games_version_nonnegative
        CHECK (version >= 0),

    CONSTRAINT ck_games_fen_nonblank
        CHECK (length(btrim(current_fen)) > 0)
);

CREATE INDEX idx_games_white_player
    ON games (white_player_id);

CREATE INDEX idx_games_black_player
    ON games (black_player_id);