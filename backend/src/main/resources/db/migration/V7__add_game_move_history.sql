CREATE TABLE game_moves (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    game_id BIGINT NOT NULL,
    sequence_number BIGINT NOT NULL,
    player_id BIGINT NOT NULL,
    from_square VARCHAR(2) NOT NULL,
    to_square VARCHAR(2) NOT NULL,
    promotion VARCHAR(10),
    resulting_fen TEXT NOT NULL,
    played_at TIMESTAMP WITH TIME ZONE NOT NULL,

    CONSTRAINT fk_game_moves_game
        FOREIGN KEY (game_id)
        REFERENCES games(id),

    CONSTRAINT fk_game_moves_player
        FOREIGN KEY (player_id)
        REFERENCES players(id),

    CONSTRAINT uq_game_moves_sequence
        UNIQUE (game_id, sequence_number),

    CONSTRAINT ck_game_moves_sequence_positive
        CHECK (sequence_number > 0),

    CONSTRAINT ck_game_moves_from_square
        CHECK (from_square ~ '^[a-h][1-8]$'),

    CONSTRAINT ck_game_moves_to_square
        CHECK (to_square ~ '^[a-h][1-8]$'),

    CONSTRAINT ck_game_moves_distinct_squares
        CHECK (from_square <> to_square),

    CONSTRAINT ck_game_moves_promotion
        CHECK (
            promotion IS NULL
            OR promotion IN ('QUEEN', 'ROOK', 'BISHOP', 'KNIGHT')
        ),

    CONSTRAINT ck_game_moves_resulting_fen_nonblank
        CHECK (length(btrim(resulting_fen)) > 0)
);

