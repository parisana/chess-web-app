CREATE TABLE auth_credentials (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    player_id BIGINT NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uk_auth_credentials_player UNIQUE (player_id),

    CONSTRAINT fk_auth_credentials_player
        FOREIGN KEY (player_id)
        REFERENCES players(id)
);
--  Why player_id is unique: each player can have only one local password credential record.
--  If we later introduce Google login, we'll revisit the authentication schema to support multiple login methods rather than forcing everything into this table.