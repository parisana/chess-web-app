CREATE TABLE matchmaking_queue (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    player_id BIGINT NOT NULL,
    enqueued_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uk_matchmaking_queue_player UNIQUE (player_id),

    CONSTRAINT fk_matchmaking_queue_player
        FOREIGN KEY (player_id)
        REFERENCES players(id)
);

CREATE INDEX idx_matchmaking_queue_order
    ON matchmaking_queue (enqueued_at, id);

-- The unique constraint enforces one entry per player, including concurrent requests. A service-level existence check alone cannot guarantee that.
-- The index supports selecting the oldest entries later. Ordering by enqueued_at, id gives a deterministic tie-breaker when timestamps match.